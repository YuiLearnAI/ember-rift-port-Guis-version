/* ============================================================
 * 新通货（余烬裂隙扩展包）
 * ------------------------------------------------------------
 * 用法：复制一段 push({...})，保存后重新构建：
 *     node 迁移工具/build/build.mjs
 * 新通货会进入通货栏、调试“全部通货”和掉落池。
 *
 * 字段说明（必填：id / n / d；其余可选）：
 *   id    唯一英文 id（建议 mods_ 开头）
 *   n     显示名
 *   v     价值（混沌石口径，用于估值/兑换）
 *   w     掉落权重（越大越常见）
 *   col   颜色（十六进制）
 *   grp   分类：basic（普通通货）/ omen（预兆）/ rune（符文）等
 *   d     说明文本
 *   like  可选：复制某个已有通货的**使用效果**（如 "chaos" 混沌石、"exalt" 崇高石）
 *         有 like 时，点这颗通货再点装备，会按 like 通货的工艺生效，但消耗的是新通货。
 *   enabled:false  可选；写 false 会跳过
 * ============================================================ */
window.RIFT_EXTRA_CURRENCIES = window.RIFT_EXTRA_CURRENCIES || [];

window.RIFT_EXTRA_CURRENCIES.push({
  id: "mods_runesmith_artificer",
  n: "符文师的工匠石",
  v: 120,
  w: 2,
  col: "#8fd0ea",
  grp: "sock",
  d: "为装备增加符文插槽，数量 = 该装备物品等级 ÷ 15（向下取整，至少 1）。新增插槽为特殊符文槽，只能放入符文之语玩法的符文。"
});
